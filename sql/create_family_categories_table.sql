  f.id as family_id,
  unnest(ARRAY['milestones', 'family', 'health', 'education', 'adventures', 'everyday']) as category_value,
  unnest(ARRAY['Milestones', 'Family', 'Health', 'Education', 'Adventures', 'Everyday Life']) as category_label,
